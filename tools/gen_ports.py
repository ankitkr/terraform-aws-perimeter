"""Regenerate lambda/perimeter/ports.py from Nmap's nmap-services file.

    python3 tools/gen_ports.py /opt/homebrew/share/nmap/nmap-services

Nmap ranks ports by how often they were found open in its Internet-wide scans; its own
--top-ports takes the most frequent TCP entries, and so do these profiles."""

import re
import sys
from pathlib import Path

LINE = re.compile(r"^\S+\s+(\d+)/tcp\s+([0-9.]+)")


def top(path, n):
    ranked = []
    for line in Path(path).read_text(errors="replace").splitlines():
        m = LINE.match(line)
        if m:
            ranked.append((-float(m.group(2)), int(m.group(1))))
    return [port for _, port in sorted(ranked)[:n]]


def wrap(ports):
    rows = [ports[i : i + 16] for i in range(0, len(ports), 16)]
    return "\n".join("    " + ", ".join(str(p) for p in row) + "," for row in rows)


def main(path):
    header = next((line for line in Path(path).read_text(errors="replace").splitlines() if "$Id" in line), "").lstrip("# ")
    out = Path(__file__).resolve().parent.parent / "lambda" / "perimeter" / "ports.py"
    out.write_text(
        f'''"""Scan profiles: the most frequently open TCP ports, in Nmap's frequency order.

Generated by tools/gen_ports.py from Nmap's nmap-services ({header or "unversioned"}),
https://svn.nmap.org/nmap/nmap-services. Don't edit by hand."""

TOP100 = (
{wrap(top(path, 100))}
)

TOP1000 = (
{wrap(top(path, 1000))}
)


def profile(name):
    """The ports of a profile: top100, top1000 or all."""
    if name == "all":
        return tuple(range(1, 65536))
    return {{"top100": TOP100, "top1000": TOP1000}}[name]
'''
    )


if __name__ == "__main__":
    main(sys.argv[1])
